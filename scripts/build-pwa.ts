/**
 * Post-processing for the web build (run after `expo export --platform web`):
 * writes dist/sw.js, a service worker that caches the whole app so it opens
 * instantly and works offline.
 *
 *   npm run web:build
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { folderReader } from './lib/fs-reader';

const dist = join(__dirname, '..', 'dist');

// The single-page web build ignores +html.tsx, so the "installable app" tags are added here.
const HEAD_TAGS = `
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    <meta name="description" content="Learn Swedish by reading illustrated stories." />
    <link rel="manifest" href="/manifest.webmanifest" />
    <meta name="theme-color" content="#FBF7F0" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="#1B1916" media="(prefers-color-scheme: dark)" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="default" />
    <meta name="apple-mobile-web-app-title" content="Saga" />
    <link rel="apple-touch-icon" href="/apple-touch-icon.png" />
    <style>
      html, body { background: #FBF7F0; }
      @media (prefers-color-scheme: dark) { html, body { background: #1B1916; } }
      html { -webkit-text-size-adjust: 100%; }
      * { -webkit-tap-highlight-color: transparent; }
      body { overscroll-behavior: none; -webkit-font-smoothing: antialiased; }
    </style>
`;
const indexPath = join(dist, 'index.html');
let html = readFileSync(indexPath, 'utf8');
html = html.replace(/<meta name="viewport"[^>]*>/, '').replace('<html lang="en">', '<html lang="sv">');
if (!html.includes('rel="manifest"')) html = html.replace('</head>', `${HEAD_TAGS}  </head>`);
writeFileSync(indexPath, html);

const files = folderReader(dist)
  .list()
  .map((f) => `/${f}`)
  .filter((f) => f !== '/sw.js' && f !== '/metadata.json')
  .sort();

const hash = createHash('sha1');
for (const f of files) hash.update(f).update(readFileSync(join(dist, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `/* Saga service worker – generated by scripts/build-pwa.ts. Do not edit. */
const CACHE = 'saga-${version}';
const FILES = ${JSON.stringify(files)};

// Installing downloads the whole app once. A new version waits until every open
// window is closed before taking over, so a running app never loses its files.
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith('saga-') && k !== CACHE).map((k) => caches.delete(k)))),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      // Page navigations always get the app shell (the app does its own routing).
      const hit = (await cache.match(req, { ignoreSearch: true })) || (req.mode === 'navigate' ? await cache.match('/index.html') : undefined);
      if (hit) return hit;
      try {
        return await fetch(req);
      } catch (e) {
        if (req.mode === 'navigate') {
          const shell = await cache.match('/index.html');
          if (shell) return shell;
        }
        throw e;
      }
    })(),
  );
});
`;

writeFileSync(join(dist, 'sw.js'), sw);
console.log(`dist/sw.js written: ${files.length} files, version ${version}`);
