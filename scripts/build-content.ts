/**
 * Content build:
 *   1. renders the bundled stories' illustrations into content/stories/<id>/…svg
 *   2. validates every package with the app's own validator
 *   3. compiles the packages into src/content/bundled/generated/*.ts (bundled in the app)
 *   4. writes importable example packages to content/dist/<id>.zip
 *
 *   npm run content:build
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { zipSync, strToU8 } from 'fflate';
import { loadStoryPackage, formatIssues } from '../src/features/import/validate';
import { canvas } from './illustrations/lib';
import { ettAr, historia, livet } from './illustrations/scenes';
import { folderReader } from './lib/fs-reader';

const ROOT = join(__dirname, '..');
const STORIES = join(ROOT, 'content', 'stories');
const OUT = join(ROOT, 'src', 'content', 'bundled', 'generated');
const DIST = join(ROOT, 'content', 'dist');

const SCENES: Record<string, Record<string, (cv: ReturnType<typeof canvas>) => string>> = {
  'sveriges-historia': historia,
  'livet-i-sverige': livet,
  'ett-ar-i-sverige': ettAr,
};

/** Stories compiled into the app, in library order. Other folders are only validated and zipped. */
const BUNDLED = ['sveriges-historia', 'livet-i-sverige', 'ett-ar-i-sverige'];

function renderIllustrations(id: string) {
  const scenes = SCENES[id];
  if (!scenes) return;
  const story = JSON.parse(readFileSync(join(STORIES, id, 'story.json'), 'utf8'));
  const jobs: { src: string; aspect: number; key: string }[] = [{ src: story.cover.src, aspect: story.cover.aspect ?? 0.75, key: 'cover' }];
  for (const ch of story.chapters) for (const p of ch.pages) if (p.image) jobs.push({ src: p.image.src, aspect: p.image.aspect ?? 4 / 3, key: p.id });
  for (const job of jobs) {
    const scene = scenes[job.key];
    if (!scene) throw new Error(`No illustration scene for ${id}/${job.key}`);
    const file = join(STORIES, id, job.src);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, scene(canvas(job.aspect, `${id}-${job.key}`)));
  }
  console.log(`  ✓ ${jobs.length} illustrations`);
}

const rank = (id: string) => (BUNDLED.includes(id) ? BUNDLED.indexOf(id) : 99);
const ids = readdirSync(STORIES).sort((a, b) => rank(a) - rank(b));
mkdirSync(OUT, { recursive: true });
mkdirSync(DIST, { recursive: true });
let failed = false;
const modules: string[] = [];

for (const id of ids) {
  console.log(`■ ${id}`);
  renderIllustrations(id);
  const dir = join(STORIES, id);
  const reader = folderReader(dir);
  const { pkg, issues } = loadStoryPackage(reader);
  if (issues.length) console.log(formatIssues(issues));
  if (!pkg) {
    failed = true;
    continue;
  }
  // Inline SVG assets for the bundle (bundled stories only).
  const assets: Record<string, string> = {};
  if (!BUNDLED.includes(id)) {
    writeZip(id, dir, reader);
    continue;
  }
  for (const path of pkg.assets) assets[path] = reader.text(path);
  const varName = id.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
  const body =
    `// GENERATED by scripts/build-content.ts from content/stories/${id}. Do not edit.\n` +
    `import type { BundledStory } from '../types';\n\n` +
    `const ${varName}: BundledStory = ${JSON.stringify({ manifest: pkg.manifest, vocabulary: pkg.vocabulary, quiz: pkg.quiz, exerciseSets: pkg.exerciseSets, assets })};\n\n` +
    `export default ${varName};\n`;
  writeFileSync(join(OUT, `${id}.ts`), body);
  modules.push(id);

  writeZip(id, dir, reader);
}

/** Writes an importable package (identical layout to what users import). */
function writeZip(id: string, dir: string, reader: ReturnType<typeof folderReader>) {
  const files: Record<string, Uint8Array> = {};
  for (const path of reader.list()) files[path] = path.endsWith('.json') || path.endsWith('.svg') ? strToU8(reader.text(path)) : readFileSync(join(dir, path));
  writeFileSync(join(DIST, `${id}.zip`), zipSync(files, { level: 9 }));
  console.log(`  ✓ ${BUNDLED.includes(id) ? 'compiled · ' : ''}content/dist/${id}.zip`);
}

const index =
  `// GENERATED by scripts/build-content.ts. Do not edit.\n` +
  `import type { BundledStory } from '../types';\n` +
  modules.map((id, i) => `import s${i} from './${id}';`).join('\n') +
  `\n\nexport const bundledStories: BundledStory[] = [${modules.map((_, i) => `s${i}`).join(', ')}];\n`;
writeFileSync(join(OUT, 'index.ts'), index);
process.exit(failed ? 1 : 0);
